DROP DATABASE IF EXISTS banking_database;
CREATE DATABASE banking_database;
USE banking_database;

-- ------------------------- TABLES --------------------------
CREATE TABLE branches (
  branch_id     INT PRIMARY KEY,
  branch_name   VARCHAR(60) NOT NULL,
  city          VARCHAR(40) NOT NULL,
  state         VARCHAR(40) NOT NULL,
  opened_date   DATE NOT NULL
);

CREATE TABLE employees (
  employee_id   INT PRIMARY KEY,
  first_name    VARCHAR(40) NOT NULL,
  last_name     VARCHAR(40) NOT NULL,
  branch_id     INT NOT NULL,
  job_title     VARCHAR(40) NOT NULL,
  salary        DECIMAL(10,2) NOT NULL,
  hire_date     DATE NOT NULL,
  manager_id    INT NULL,
  FOREIGN KEY (branch_id)  REFERENCES branches(branch_id),
  FOREIGN KEY (manager_id) REFERENCES employees(employee_id)
);

CREATE TABLE customers (
  customer_id    INT PRIMARY KEY,
  first_name     VARCHAR(40) NOT NULL,
  last_name      VARCHAR(40) NOT NULL,
  gender         CHAR(1) NOT NULL,
  date_of_birth  DATE NOT NULL,
  email          VARCHAR(80) NULL,
  phone          VARCHAR(15) NULL,
  city           VARCHAR(40) NOT NULL,
  state          VARCHAR(40) NOT NULL,
  occupation     VARCHAR(30) NOT NULL,
  join_date      DATE NOT NULL,
  branch_id      INT NOT NULL,
  FOREIGN KEY (branch_id) REFERENCES branches(branch_id)
);

CREATE TABLE account_types (
  type_id        INT PRIMARY KEY,
  type_name      VARCHAR(30) NOT NULL,
  min_balance    DECIMAL(12,2) NOT NULL,
  interest_rate  DECIMAL(5,2) NOT NULL
);

CREATE TABLE accounts (
  account_id      INT PRIMARY KEY,
  account_number  VARCHAR(15) NOT NULL UNIQUE,
  customer_id     INT NOT NULL,
  type_id         INT NOT NULL,
  branch_id       INT NOT NULL,
  open_date       DATE NOT NULL,
  close_date      DATE NULL,
  balance         DECIMAL(15,2) NOT NULL,
  status          VARCHAR(10) NOT NULL,
  FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
  FOREIGN KEY (type_id)     REFERENCES account_types(type_id),
  FOREIGN KEY (branch_id)   REFERENCES branches(branch_id)
);

CREATE TABLE cards (
  card_id       INT PRIMARY KEY,
  account_id    INT NOT NULL,
  card_type     VARCHAR(10) NOT NULL,
  issue_date    DATE NOT NULL,
  expiry_date   DATE NOT NULL,
  status        VARCHAR(10) NOT NULL,
  credit_limit  DECIMAL(12,2) NULL,
  FOREIGN KEY (account_id) REFERENCES accounts(account_id)
);

CREATE TABLE transactions (
  transaction_id  INT PRIMARY KEY,
  account_id      INT NOT NULL,
  txn_date        DATE NOT NULL,
  txn_type        VARCHAR(15) NOT NULL,
  amount          DECIMAL(12,2) NOT NULL,
  channel         VARCHAR(10) NOT NULL,
  description     VARCHAR(60) NULL,
  FOREIGN KEY (account_id) REFERENCES accounts(account_id)
);

CREATE TABLE loan_types (
  loan_type_id         INT PRIMARY KEY,
  loan_type_name       VARCHAR(30) NOT NULL,
  base_interest_rate   DECIMAL(5,2) NOT NULL
);

CREATE TABLE loans (
  loan_id           INT PRIMARY KEY,
  customer_id       INT NOT NULL,
  loan_type_id      INT NOT NULL,
  branch_id         INT NOT NULL,
  approved_by       INT NOT NULL,
  principal_amount  DECIMAL(14,2) NOT NULL,
  interest_rate     DECIMAL(5,2) NOT NULL,
  start_date        DATE NOT NULL,
  term_months       INT NOT NULL,
  status            VARCHAR(10) NOT NULL,
  FOREIGN KEY (customer_id)  REFERENCES customers(customer_id),
  FOREIGN KEY (loan_type_id) REFERENCES loan_types(loan_type_id),
  FOREIGN KEY (branch_id)    REFERENCES branches(branch_id),
  FOREIGN KEY (approved_by)  REFERENCES employees(employee_id)
);

CREATE TABLE loan_payments (
  payment_id      INT PRIMARY KEY,
  loan_id         INT NOT NULL,
  payment_date    DATE NOT NULL,
  amount_paid     DECIMAL(12,2) NOT NULL,
  payment_status  VARCHAR(10) NOT NULL,
  late_fee        DECIMAL(8,2) NOT NULL DEFAULT 0,
  FOREIGN KEY (loan_id) REFERENCES loans(loan_id)
);

